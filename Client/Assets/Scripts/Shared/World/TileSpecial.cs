namespace Shared.World
{
    /// <summary>
    /// Спец-роль тайла для переходов между этажами. Статическая разметка карты
    /// (ставится в редакторе), читается симуляцией при использовании (E/клик).
    /// Двери — отдельно (Tile.DoorType), т.к. у них динамическое состояние.
    /// </summary>
    public enum TileSpecial : byte
    {
        None = 0,
        StairUp = 1,   // ведёт на этаж z+1 (парная StairDown на z+1, та же X/Y)
        StairDown = 2, // ведёт на этаж z-1
        Lift = 3,      // часть шахты лифта; соединяется по колонке (одинаковые X/Y)
        Spawn = 4      // точка появления игрока (ставится в редакторе)
    }
}
